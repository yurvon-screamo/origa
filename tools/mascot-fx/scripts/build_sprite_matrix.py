#!/usr/bin/env python3
"""Build mascot/origa.js from records/<dir>/matrix.txt (single source: the
cleaned generated sprite). Generates the BASE pose and a BLINK pose (eyes
closed = dark lids) by locating the eye zone via pupil characters ("p").

Usage: python scripts/build_sprite_matrix.py records/from-user-128
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "records" / "from-user-128"
lines = src_dir.joinpath("matrix.txt").read_text(encoding="utf-8").splitlines()
W, H = len(lines[0]), len(lines)

# Halo cleanup: the generator's cream background snaps to the white palette
# entry ("w") and stays opaque as a pale frame around the figure. Eat every
# "w" reachable from the matrix border through w-only pixels: the outer halo
# goes, while whites INSIDE the figure (drawstrings, eye whites, sneaker
# panels) are walled off by hair/hood/outline and survive.
wset = {(x, y) for y in range(H) for x in range(W) if lines[y][x] == "w"}

def touches_transparent(x, y):
    return any(
        0 <= nx < W and 0 <= ny < H and lines[ny][nx] == "."
        for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1))
    )

edge_seeds = {
    (x, y)
    for y in range(H)
    for x in range(W)
    if lines[y][x] == "w" and (x in (0, W - 1) or y in (0, H - 1) or touches_transparent(x, y))
}
while edge_seeds:
    x, y = edge_seeds.pop()
    wset.discard((x, y))
    lines[y] = lines[y][:x] + "." + lines[y][x + 1 :]
    for nx, ny in ((x - 1, y), (x + 1, y), (x, y - 1), (x, y + 1)):
        if 0 <= nx < W and 0 <= ny < H and (nx, ny) in wset:
            edge_seeds.add((nx, ny))

# eye zone: connected components of pupil pixels ("p"), the two biggest
# clusters are the eyes; stray pinkish noise pixels are ignored
pts = [(x, y) for y in range(H) for x, ch in enumerate(lines[y]) if ch == "p"]
pset = set(pts)
clusters = []
while pset:
    seed = pset.pop()
    comp, q = [seed], [seed]
    while q:
        x, y = q.pop()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (x + dx, y + dy)
            if n in pset:
                pset.discard(n)
                comp.append(n)
                q.append(n)
    clusters.append(comp)
clusters.sort(key=len, reverse=True)
eyes = [c for c in clusters if len(c) >= 8][:2]
if not eyes:
    sys.exit("no pupil clusters found — cannot place the blink pose")
xs = [x for c in eyes for x, _ in c]
ys = [y for c in eyes for _, y in c]
x_l, x_r = min(xs) - 1, max(xs) + 1
y_top, y_bot = min(ys) - 1, max(ys) + 1
print(f"eye zone: rows {y_top}..{y_bot}, cols {x_l}..{x_r}")

# blink: dark lid lines over the lenses. Eye zone calibrated visually per
# sprite scale (auto-detection confuses brown lips with brown eyes).
BLINK_CALIBRATION = {
    128: {"spans": [(50, 63), (71, 84)], "rows": (47, 51)},
    64: {"spans": [(26, 42)], "rows": (24, 26)},
}
cal = BLINK_CALIBRATION[W]
blink = [list(row) for row in lines]
for y in range(cal["rows"][0], cal["rows"][1] + 1):
    for x_l, x_r in cal["spans"]:
        for x in range(x_l, x_r + 1):
            if blink[y][x] != ".":
                blink[y][x] = "k"
blink_rows = ["".join(r) for r in blink]
EYE_ROW = cal["rows"][0]
EYE_L0, EYE_R0 = cal["spans"][0]

def js_rows(rows):
    inner = ",\n".join(f'    "{r}"' for r in rows)
    return f"[\n{inner}\n  ]"

out = f'''// Origa mascot as a code sprite: {W}x{H} ASCII matrices, feet at (0, 0).
// GENERATED by scripts/build_sprite_matrix.py from the art-directed sprite
// (image-to-image on the logo, snapped to the Origa palette). Poses are row
// patches of the base matrix. Character map lives in palette.js.
import {{ hex }} from "pixelfx";
import {{ PAL }} from "./palette.js";

export const W = {W};
export const H = {H};

// Standing easy, eyes open, arms in sleeves along the body.
const BASE = {js_rows(lines)};

// Blink: same body, eyes closed (dark lids inside the rims).
const BLINK = {js_rows(blink_rows)};

export const POSES = {{ idle: BASE, blink: BLINK }};

/**
 * Draw the mascot with its feet at local (0, 0): centered on x, standing on y.
 * p: pixelfx Painter; pose: one of POSES (default idle); opts.alpha fades the
 * whole sprite (spawn-from-poof entrances).
 */
export function draw(p, pose = POSES.idle, opts = {{}}) {{
  p.sprite(pose, PAL, -W / 2, -H, opts.alpha !== undefined ? {{ a: opts.alpha }} : undefined);
}}

/**
 * The mascot in the pixelfx `o.actor` contract (mask + packed pixels + body
 * landmarks), so onBody library effects (status, level-up, heal) can paint
 * on and around our figure. Eyes are the calibrated blink-line positions.
 */
export function mascotActor(pose = POSES.idle) {{
  const mask = {{ w: W, h: H, data: new Uint8Array(W * H) }};
  const pixels = new Uint32Array(W * H);
  for (let y = 0; y < H; y++) {{
    for (let x = 0; x < W; x++) {{
      const ch = pose[y][x];
      if (ch === ".") continue;
      mask.data[y * W + x] = 1;
      pixels[y * W + x] = hex(PAL[ch]);
    }}
  }}
  // eye line sits ~{EYE_ROW} rows from the top -> -{H - EYE_ROW} from the feet
  const eyeY = -({H - EYE_ROW});
  const x0 = -Math.floor(W / 2);
  return {{
    mask,
    pixels,
    x: x0,
    y: -H,
    w: W,
    h: H,
    k: 1,
    head: [0, -H],
    chest: [0, -Math.floor(H * 0.62)],
    eyes: [
      [x0 + {EYE_L0}, eyeY],
      [x0 + {EYE_R0}, eyeY],
    ],
  }};
}}
'''

(ROOT / "mascot" / "origa.js").write_text(out, encoding="utf-8")
print(f"wrote mascot/origa.js ({W}x{H}, {len(lines)} base rows)")
